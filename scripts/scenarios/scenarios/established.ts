/**
 * `established` — months of ordinary, consistent use. The default demo state.
 *
 * Three 5-week Push / Pull / Legs blocks (scheduled deload every 5 weeks):
 * Hypertrophy Block 1 and 2 are archived; Block 3 is active and in week 3.
 * Weeks start two days before the anchor, so this week's Push day is logged,
 * today is Pull (still to do), Legs is upcoming.
 *
 * About twelve weeks of history, generated by double progression with a
 * seeded PRNG (uneven last sets, weeks without a rep gained). Ordinary life:
 * one Block 1 leg day simply missed; week 2 of Block 1 trained at Campus Rec
 * Center (since archived) on its own machines; in Block 3 one Pull day was
 * skipped and one Push day logged late, both via the missed-day flow's dated
 * records. Block 3 adds a little cardio (type + minutes).
 *
 * Intended derived states (proved in verify): Bench and Barbell Row are ready
 * for Progress; every other lift is a plain Hold; trends have ~10 points;
 * four active goals sit between ~70% and ~95%; one Overhead Press goal was
 * reached during Block 2 (completed by the real completion engine).
 */

const GYM_VARIABLE = new Set<ExerciseKey>([
  "PULLDOWN",
  "CABLE_ROW",
  "PUSHDOWN",
  "LEG_PRESS",
  "LEG_CURL",
]);

const SESSIONS: SessionSpec[] = [
  {
    key: "push",
    name: "Push Day",
    dayOffset: 0,
    slots: [
      { ex: "BENCH", sets: 3, repMin: 6, repMax: 8 },
      { ex: "OHP", sets: 3, repMin: 8, repMax: 10 },
      { ex: "INCLINE_DB", sets: 3, repMin: 8, repMax: 12 },
      { ex: "PUSHDOWN", sets: 3, repMin: 10, repMax: 12 },
      { ex: "LATERAL", sets: 3, repMin: 12, repMax: 15 },
    ],
  },
  {
    key: "pull",
    name: "Pull Day",
    dayOffset: 2,
    slots: [
      { ex: "ROW", sets: 3, repMin: 6, repMax: 8 },
      { ex: "PULLDOWN", sets: 3, repMin: 8, repMax: 10 },
      { ex: "CABLE_ROW", sets: 3, repMin: 10, repMax: 12 },
      { ex: "CURL", sets: 3, repMin: 10, repMax: 12 },
    ],
  },
  {
    key: "legs",
    name: "Leg Day",
    dayOffset: 4,
    slots: [
      { ex: "SQUAT", sets: 3, repMin: 5, repMax: 7 },
      { ex: "RDL", sets: 3, repMin: 8, repMax: 10 },
      { ex: "LEG_PRESS", sets: 3, repMin: 10, repMax: 12 },
      { ex: "LEG_CURL", sets: 3, repMin: 10, repMax: 12 },
    ],
  },
];

/** Starting load and increment per lift (lbs). */
const LOADS: Record<string, { start: number; increment: number }> = {
  BENCH: { start: 165, increment: 5 },
  OHP: { start: 95, increment: 5 },
  INCLINE_DB: { start: 50, increment: 5 },
  PUSHDOWN: { start: 45, increment: 5 },
  LATERAL: { start: 15, increment: 5 },
  ROW: { start: 135, increment: 5 },
  PULLDOWN: { start: 110, increment: 5 },
  CABLE_ROW: { start: 100, increment: 5 },
  CURL: { start: 25, increment: 5 },
  SQUAT: { start: 205, increment: 10 },
  RDL: { start: 165, increment: 10 },
  LEG_PRESS: { start: 270, increment: 20 },
  LEG_CURL: { start: 80, increment: 5 },
};

const PROGRESS_NOW: ExerciseKey[] = ["BENCH", "ROW"];

function timeline(anchorIso: string) {
  const s3 = addDays(anchorIso, -16);
  const s2 = addDays(s3, -35);
  const s1 = addDays(s2, -35);
  const block = (
    key: string,
    n: number,
    startIso: string,
    status: "active" | "archived",
  ): MesocycleSpec => ({
    key,
    name: `Hypertrophy Block ${n}`,
    splitType: "ppl",
    status,
    startIso,
    lengthWeeks: 5,
    deloadEveryWeeks: 5,
    sessions: SESSIONS,
  });
  const mesocycles = [
    block("b1", 1, s1, "archived"),
    block("b2", 2, s2, "archived"),
    {
      ...block("b3", 3, s3, "active"),
      cardio: [
        { dayOffset: 1, type: "Incline Walk", durationMin: 20 },
        { dayOffset: 5, type: "Bike", durationMin: 30 },
      ],
    },
  ];
  const at = (meso: string, week: number, offset: number) =>
    addDays(
      mesocycles.find((m) => m.key === meso)!.startIso,
      (week - 1) * 7 + offset,
    );
  return { mesocycles, at, s1, s3 };
}

function build(anchorIso: string): ScenarioFacts {
  const { mesocycles, at, s1, s3 } = timeline(anchorIso);

  const skipped = at("b3", 1, 2); // Block 3 week 1 Pull — skipped
  const loggedLate = at("b3", 2, 0); // Block 3 week 2 Push — logged late
  const missedB1 = at("b1", 3, 4); // Block 1 week 3 Legs — just missed
  const resolutions: ResolutionSpec[] = [
    { meso: "b3", missedOn: skipped, outcome: "skipped" },
    { meso: "b3", missedOn: loggedLate, outcome: "logged_late" },
  ];

  const trained: (Occurrence & { gym: string })[] = mesocycles
    .flatMap(occurrences)
    .filter(
      (o) => o.date < anchorIso && o.date !== skipped && o.date !== missedB1,
    )
    .map((o) => ({
      ...o,
      gym: o.meso === "b1" && o.week === 2 ? "campus" : "downtown",
    }));

  // One continuous double-progression history per lift, across all blocks.
  const setsByLift = new Map<string, SetSpec[]>(); // `${ex}|${date}` → sets
  for (const session of SESSIONS) {
    const occ = trained.filter((o) => o.session === session.key);
    for (const slot of session.slots) {
      const kinds: OccurrenceKind[] = occ.map((o) =>
        o.deload
          ? "deload"
          : o.gym === "campus" && GYM_VARIABLE.has(slot.ex)
            ? "away"
            : "normal",
      );
      const history = doubleProgression(kinds, {
        seed: `established|${slot.ex}`,
        ...LOADS[slot.ex],
        repMin: slot.repMin,
        repMax: slot.repMax,
        sets: slot.sets,
        awayFactor: 0.8,
        finish: PROGRESS_NOW.includes(slot.ex) ? "progress" : "hold",
      });
      occ.forEach((o, i) => setsByLift.set(`${slot.ex}|${o.date}`, history[i]));
    }
  }

  const workouts: WorkoutSpec[] = trained.map((o) => ({
    meso: o.meso,
    session: o.session,
    scheduledFor: o.date,
    gym: o.gym,
    exercises: SESSIONS.find((s) => s.key === o.session)!.slots.map((sl) => ({
      ex: sl.ex,
      sets: setsByLift.get(`${sl.ex}|${o.date}`)!,
    })),
  }));

  // Goals: targets the lifter would pick — a stretch above current bests.
  const best = (ex: ExerciseKey, gym?: string, before?: string) =>
    Math.max(
      0,
      ...trained
        .filter(
          (o) =>
            !o.deload &&
            (!gym || o.gym === gym) &&
            (!before || o.date < before) &&
            setsByLift.has(`${ex}|${o.date}`),
        )
        .map((o) => sessionE1rm(setsByLift.get(`${ex}|${o.date}`)!)),
    );
  const stretch = (e1rm: number, reps: number, ratio: number) =>
    Math.ceil(e1rm / ratio / (1 + reps / 30) / 5) * 5;
  const goals: GoalSpec[] = [
    {
      key: "bench",
      ex: "BENCH",
      reps: 5,
      ratio: 0.92,
      created: at("b3", 1, 1),
    },
    {
      key: "squat",
      ex: "SQUAT",
      reps: 5,
      ratio: 0.86,
      created: at("b2", 2, 5),
    },
    {
      key: "pulldown",
      ex: "PULLDOWN",
      reps: 10,
      ratio: 0.8,
      created: at("b3", 1, 3),
      gym: "downtown",
    },
    { key: "rdl", ex: "RDL", reps: 8, ratio: 0.74, created: at("b2", 1, 5) },
  ].map((g) => ({
    key: g.key,
    ex: g.ex as ExerciseKey,
    gym: g.gym,
    targetWeightLbs: stretch(best(g.ex as ExerciseKey, g.gym), g.reps, g.ratio),
    targetReps: g.reps,
    createdIso: g.created,
  }));

  // A reached goal: Overhead Press, set in Block 1 week 1 at the best set
  // Block 2 would eventually produce; completed by the real engine on the
  // first session whose e1RM meets it.
  const ohpSessions = trained
    .filter((o) => o.session === "push" && !o.deload && o.meso !== "b3")
    .map((o) => ({ date: o.date, sets: setsByLift.get(`OHP|${o.date}`)! }));
  const ohpTop = ohpSessions
    .flatMap((s) => s.sets)
    .reduce((a, b) =>
      estimateOneRepMax(b.weightLbs, b.reps) >
      estimateOneRepMax(a.weightLbs, a.reps)
        ? b
        : a,
    );
  const ohpTarget = estimateOneRepMax(ohpTop.weightLbs, ohpTop.reps);
  const reachedOn = ohpSessions.find(
    (s) => sessionE1rm(s.sets) >= ohpTarget - 1e-9,
  )!.date;
  goals.push({
    key: "ohp-reached",
    ex: "OHP",
    targetWeightLbs: ohpTop.weightLbs,
    targetReps: ohpTop.reps,
    createdIso: addDays(s1, 1),
    reconcileOn: reachedOn,
  });

  const cardioLogs: CardioLogSpec[] = [
    {
      meso: "b3",
      scheduledFor: at("b3", 1, 1),
      type: "Incline Walk",
      durationMin: 22,
    },
    { meso: "b3", scheduledFor: at("b3", 1, 5), type: "Bike", durationMin: 30 },
    {
      meso: "b3",
      scheduledFor: at("b3", 2, 1),
      type: "Incline Walk",
      durationMin: 20,
    },
    // Week 2's Bike was missed (shows as Missed in History).
    { meso: "b3", scheduledFor: at("b3", 3, 1), type: "Bike", durationMin: 25 },
  ].filter((c) => c.scheduledFor < anchorIso);

  return {
    gyms: [
      {
        key: "downtown",
        name: "Downtown Gym",
        address: "Downtown, near the river",
      },
      {
        key: "campus",
        name: "Campus Rec Center",
        address: "University campus, north lot",
        archivedIso: addDays(s3, -3),
      },
    ],
    mesocycles,
    workouts,
    resolutions,
    cardioLogs,
    goals,
  };
}

export const established: Scenario = {
  key: "established",
  description:
    "Long-running lifter with mature trends, goals, and history (default demo).",
  shows: [
    "~12 weeks across three Push/Pull/Legs blocks (two archived, one active in week 3)",
    "Today is Pull Day; Barbell Row shows Progress on the dashboard",
    "Barbell Bench Press and Barbell Row: Progress; every other lift: Hold (no tag)",
    "Multi-point e1RM trends with scheduled-deload weeks marked",
    "Four active goals (~70–95%) and one reached Overhead Press goal in history",
    "Week view with a skipped day, a logged-late day, cardio logged / missed / upcoming",
    "An archived gym (Campus Rec Center) still named in old workouts",
  ],
  build,
  async verify(ctx) {
    const firstWorkout = ctx.facts.workouts
      .map((w) => w.scheduledFor)
      .sort()[0];
    ctx.check(
      firstWorkout <= addDays(ctx.anchorIso, -70),
      `History should span at least 10 weeks; it starts ${firstWorkout}`,
    );
    for (const session of SESSIONS) {
      for (const { ex } of session.slots) {
        const p = await ctx.progression(
          ex,
          GYM_VARIABLE.has(ex) ? "downtown" : undefined,
        );
        ctx.note(describe(p));
        const expected = PROGRESS_NOW.includes(ex) ? "progress" : "hold";
        ctx.check(
          p.state === expected,
          `${p.exerciseName} should derive ${expected}; the engine derived ${p.state}`,
        );
        ctx.check(
          p.isGymVariable === GYM_VARIABLE.has(ex),
          `${p.exerciseName}: gym-variable classification differs from the scenario's assumption`,
        );
        ctx.check(
          p.points.length >= 8,
          `${p.exerciseName} should have a multi-point trend; derived ${p.points.length} points`,
        );
      }
    }
    const active = await ctx.activeGoals();
    ctx.check(
      active.length === 4,
      `Expected 4 active goals; found ${active.length}`,
    );
    for (const g of active) {
      ctx.note(
        `Goal ${g.exerciseName}${g.gymName ? ` @ ${g.gymName}` : ""} ${g.targetLabel}: ${g.percent}%`,
      );
      ctx.check(
        g.percent !== null && g.percent >= 60 && g.percent < 100,
        `${g.exerciseName} goal should be measured between 60% and 99%; derived ${g.percent}`,
      );
    }
    const history = await ctx.goalHistory();
    ctx.check(
      history.some(
        (g) =>
          g.goalId === ctx.ids.goals["ohp-reached"] &&
          g.outcome === "completed",
      ),
      "The Overhead Press goal should be in history as reached",
    );
  },
};
